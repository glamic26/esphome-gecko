#!/usr/bin/env python3
"""Turn an ESPHome DEBUG log into a replay fixture for tests/.

Reads log text (chronological order) and keeps only the raw frames the Arduino
proxy reported ("Proxy: RX:<len>:<hex>"). Everything else, including log
timestamps, is discarded.

Values that record when the capture was taken are replaced before writing:
  * 22-byte clock message: hour, minute and second become 12:00:00, and a real
    date (if present) becomes 2000-01-01.
  * Status block "Hours" byte (geckolib offset 256): becomes 12.
  * 77-byte reminder message: dropped (it carries maintenance dates).
Checksums of every changed frame are recomputed (XOR of all preceding bytes).

Usage: sanitise_capture.py INPUT.log OUTPUT.rx [--note "text"]
"""

import argparse
import re
import sys

RX_RE = re.compile(r"Proxy: RX:(\d+):([0-9A-Fa-f]+)")
HEADER_LEN = 16
NEUTRAL_HOUR = 0x0C

# Known complete-message layouts: total length -> offset of the status block.
STATUS_OFFSETS = {145: 0, 162: 0, 353: 208, 390: 228}
STATUS_HOURS_BYTE = 2  # geckolib offset 256 minus 254


def checksum(frame: bytearray) -> int:
    x = 0
    for b in frame[:-1]:
        x ^= b
    return x


def is_single(frame: bytes) -> bool:
    n = len(frame)
    return n in (15, 18, 33, 77) or (n == 22 and frame[13] == 0x4B)


def sanitise(frames):
    out = []
    dropped = 0
    pending = []  # indices into out of the current multi-part message
    for raw in frames:
        f = bytearray(raw)
        if checksum(f) != f[-1]:
            raise ValueError(f"checksum mismatch in input frame {f.hex()}")
        if len(f) == 77 and f[6] == 0x0B:
            dropped += 1
            continue
        if len(f) == 22 and f[13] == 0x4B:
            if f[14] != 0xFF:
                f[14], f[15], f[16], f[17] = 0x00, 0x01, 0x01, 0x06
            f[18], f[19], f[20] = NEUTRAL_HOUR, 0x00, 0x00
            f[-1] = checksum(f)
            out.append(f)
            continue
        out.append(f)
        # Spa-initiated messages (byte 6 = 0x0B) are a separate stream and can
        # be interleaved with config/status parts; leave them out of reassembly.
        if is_single(f) or len(f) < HEADER_LEN or f[1] != 0x09 or f[6] == 0x0B:
            continue
        pending.append(len(out) - 1)
        if f[9] == 0x01:
            continue
        # Complete message: locate the status block and patch the Hours byte.
        payload_map = []  # buffer offset -> (frame index, byte index)
        for idx in pending:
            for j in range(HEADER_LEN, len(out[idx])):
                payload_map.append((idx, j))
        pending = []
        start = STATUS_OFFSETS.get(len(payload_map))
        if start is None:
            continue
        fi, bi = payload_map[start + STATUS_HOURS_BYTE]
        out[fi][bi] = NEUTRAL_HOUR
        out[fi][-1] = checksum(out[fi])
    return out, dropped


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("input")
    ap.add_argument("output")
    ap.add_argument("--note", action="append", default=[], help="comment line written at the top")
    args = ap.parse_args()

    frames = []
    with open(args.input, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = RX_RE.search(line)
            if not m:
                continue
            n, hexs = int(m.group(1)), m.group(2)
            if len(hexs) != 2 * n:
                print(f"skipping truncated frame of declared length {n}", file=sys.stderr)
                continue
            frames.append(bytes.fromhex(hexs))

    out, dropped = sanitise(frames)
    with open(args.output, "w", encoding="ascii") as fh:
        for note in args.note:
            fh.write(f"# {note}\n")
        fh.write("# Generated by tools/sanitise_capture.py. One proxy line per frame.\n")
        for f in out:
            fh.write(f"RX:{len(f)}:{f.hex().upper()}\n")
    print(f"{len(out)} frames written, {dropped} reminder frames dropped", file=sys.stderr)


if __name__ == "__main__":
    main()
